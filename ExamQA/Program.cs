                      "«Ты опять всё сломал»",
                      "«Это твоя вина»"},
                Hash("«В таком-то сценарии происходит X, это приводит к Y, предлагаю шаг Z»")),
            ("Обсуждение на встрече перешло в обвинения. Что делать QA?",
                new[]{"Вернуться к фактам, попросить конкретику и зафиксировать договорённость письменно",
                      "Ответить тем же",
                      "Уйти со встречи"},
                Hash("Вернуться к фактам, попросить конкретику и зафиксировать договорённость письменно")),
            ("Что означает жёсткое содержание при нейтральном тоне?",
                new[]{"Прямое no-go при блокере, но без обвинений",
                      "Грубость, замаскированная вежливостью",
                      "Отказ обсуждать проблему"},
                Hash("Прямое no-go при блокере, но без обвинений")),
        };

        // Перемешиваем весь банк — вопросы идут в случайном порядке.
        Random rnd = new Random();
        var shuffledBank = bank.OrderBy(x => rnd.Next()).ToList();
        var selected = shuffledBank.Take(5).ToList();

        int score = 0;

        for (int i = 0; i < selected.Count; i++)
        {
            Console.Clear();
            Console.WriteLine("Вопрос " + (i + 1) + " из 5");
            Console.WriteLine();

            var q = selected[i];

            // Перемешиваем варианты ответа.
            var shuffledOptions = q.O.OrderBy(x => rnd.Next()).ToList();

            // Находим правильный ответ после перемешивания: сравниваем хеши.
            int correctIndex = -1;
            for (int j = 0; j < shuffledOptions.Count; j++)
            {
                if (Hash(shuffledOptions[j]) == q.H)
                {
                    correctIndex = j + 1;
                    break;
                }
            }

            Console.WriteLine(q.Q);
            for (int j = 0; j < shuffledOptions.Count; j++)
                Console.WriteLine("   " + (j + 1) + ") " + shuffledOptions[j]);

            Console.Write("Ваш ответ: ");
            string input = Console.ReadLine();

            if (int.TryParse(input, out int ans) && ans == correctIndex)
            {
                Console.WriteLine("Верно.");
                score++;
            }
            else
            {
                Console.WriteLine("Неверно.");
            }

            Console.WriteLine();
            Console.WriteLine("Нажмите Enter для продолжения.");
            Console.ReadLine();
        }

        Console.Clear();
        Console.WriteLine("ЭКЗАМЕН ЗАВЕРШЁН");
        Console.WriteLine();
        Console.WriteLine("Правильных ответов: " + score + " из 5");

        if (score == 5) Console.WriteLine("Оценка: 5");
        else if (score == 4) Console.WriteLine("Оценка: 4");
        else if (score == 3) Console.WriteLine("Оценка: 3");
        else Console.WriteLine("Оценка: 2");

        Console.WriteLine();
        Console.WriteLine("Нажмите Enter для выхода.");
        Console.ReadLine();
    }
